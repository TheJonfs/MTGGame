/**
 * pnpm nothingdear:census [--out file.md]
 *
 * S72 Part 4 (Meliyan's gate, the second gate format with a field; Bodies is the pattern): nothing that costs more
 * than four (`maxManaValue: 4` — a land is exempt; X counts as zero, CR 202.3e), the Power banned as in Bodies, the
 * High Grounds restricted to one, the laws banned as everywhere. The census: the legal pool by colour and curve; what
 * leaves (the Power, and every nonland card above four that a registered list plays); every registered Open and triad
 * list's cut — its Power slots and its cards above four — so the seeds can be the lists that pass with the fewest
 * swaps. It changes nothing.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadCardPool } from "@shandalar/cards/loader";
import { cardColors, manaValue, parseManaCost, type CardDef } from "@shandalar/cards";
import { FORMAT_DECKS } from "@shandalar/sim/open-decks";
import { NOTHING_DEAR_FORMAT, POWER_IDS } from "./formats.js";
import { cardLegal } from "./constructed-builder.js";

const arg = (k: string, d: string) => { const i = process.argv.indexOf(`--${k}`); return i >= 0 ? process.argv[i + 1]! : d; };
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const pool = loadCardPool(join(ROOT, "data/cards")).cards;
const rule = NOTHING_DEAR_FORMAT.rule;
const mv = (d: CardDef) => manaValue(parseManaCost(d.manaCost));
const isLand = (d: CardDef) => d.types.includes("Land");
const isCreature = (d: CardDef) => d.types.includes("Creature");
const POWER = new Set<string>(POWER_IDS);
const colourKey = (d: CardDef) => { const c = cardColors(d); return c.length === 0 ? "C" : c.length > 1 ? "multi" : c[0]!; };
const COLS = ["W", "U", "B", "R", "G", "multi", "C"];
const NAME: Record<string, string> = { W: "White", U: "Blue", B: "Black", R: "Red", G: "Green", multi: "Multicolour", C: "Colourless" };

const nonland = [...pool.values()].filter((d) => !d.isTokenDef && !isLand(d));
const legal = nonland.filter((d) => cardLegal(d, rule));
const { maxManaValue: _cap, ...uncapped } = rule;
const openLegal = nonland.filter((d) => cardLegal(d, { ...uncapped, banned: (rule.banned ?? []).filter((b) => !POWER.has(b)) }));
const L: string[] = [];
L.push("# Nothing Dear — a census (S72 Part 4)", "", `*Generated by \`pnpm nothingdear:census\`. Meliyan's gate: "${NOTHING_DEAR_FORMAT.note}". The Open's pool with two rules: no nonland card above mana value four (an X counts as zero), and the Power banned as in Bodies (${POWER_IDS.length} cards); the High Grounds one each; the laws banned.*`, "");
L.push(`**${legal.length} nonland cards legal** of the Open's ${openLegal.length} (${legal.filter(isCreature).length} creatures). ${openLegal.length - legal.length} leave: ${openLegal.filter((d) => POWER.has(d.id)).length} of the Power and ${openLegal.filter((d) => !POWER.has(d.id) && mv(d) > 4).length} above four.`, "");

L.push("## 1. The legal pool by colour and mana value", "", "| colour | cards | creatures | 0–1 | 2 | 3 | 4 |", "|---|---|---|---|---|---|---|");
for (const c of COLS) { const xs = legal.filter((d) => colourKey(d) === c), at = (n: number) => xs.filter((d) => (n === 1 ? mv(d) <= 1 : mv(d) === n)).length; L.push(`| ${NAME[c]} | ${xs.length} | ${xs.filter(isCreature).length} | ${at(1)} | ${at(2)} | ${at(3)} | ${at(4)} |`); }
L.push("");

type List = { key: string; name: string; archetype: string; decklist: { cardId: string; count: number }[]; sideboard?: { cardId: string; count: number }[]; archived?: boolean };
const seen = new Set<string>();
const lists: { f: string; l: List }[] = [];
for (const [f, ls] of Object.entries(FORMAT_DECKS)) {
  if (f === "peasant" || f === "bodies") continue; // Peasant has no Power and no curve above its tiers; Bodies' lists are the Open's without the Power
  for (const l of Object.values(ls) as List[]) { if (l.archived) continue; const k = JSON.stringify([...l.decklist].sort((x, y) => x.cardId.localeCompare(y.cardId))); if (seen.has(k)) continue; seen.add(k); lists.push({ f, l }); }
}
const cutOf = (l: List) => {
  const power = l.decklist.filter((e) => POWER.has(e.cardId));
  const high = l.decklist.filter((e) => { const d = pool.get(e.cardId); return d && !isLand(d) && !POWER.has(e.cardId) && mv(d) > 4; });
  const other = l.decklist.filter((e) => { const d = pool.get(e.cardId); return d && !POWER.has(e.cardId) && !(mv(d) > 4 && !isLand(d)) && !cardLegal(d, rule); });
  const n = (xs: { count: number }[]) => xs.reduce((a, e) => a + e.count, 0);
  return { power, high, other, nPower: n(power), nHigh: n(high), nOther: n(other) };
};

// 2. what leaves: the cards above four that registered lists play
const use = new Map<string, { copies: number; lists: string[] }>();
for (const { f, l } of lists) for (const e of cutOf(l).high) { const u = use.get(e.cardId) ?? { copies: 0, lists: [] }; u.copies += e.count; u.lists.push(`${l.name} (${f})`); use.set(e.cardId, u); }
L.push(`## 2. What leaves: the cards above four in the ${lists.length} registered Open and triad lists`, "", "| card | mana value | type | copies | lists |", "|---|---|---|---|---|");
for (const [id, u] of [...use].sort((a, b) => b[1].lists.length - a[1].lists.length || b[1].copies - a[1].copies)) { const d = pool.get(id)!; L.push(`| ${d.name} | ${mv(d)} | ${d.types.join(" ")} | ${u.copies} | ${u.lists.length}: ${[...new Set(u.lists)].join(", ")} |`); }
L.push("");

// 3. every list's cut
const rows = lists.map(({ f, l }) => ({ f, l, ...cutOf(l) })).sort((a, b) => a.nHigh - b.nHigh || a.nPower - b.nPower);
L.push("## 3. Every registered list's cut (fewest cards above four first)", "", "A list **passes unchanged** past the Power when it plays nothing above four. Its Power slots are refilled as Bodies' were; its cards above four are what it loses at the top.", "", "| list | format | archetype | Power slots | above four | what it loses at the top |", "|---|---|---|---|---|---|");
for (const r of rows) L.push(`| ${r.l.name} | ${r.f} | ${r.l.archetype} | ${r.nPower} | ${r.nHigh}${r.nOther ? ` (+${r.nOther} other)` : ""} | ${r.high.map((e) => `${e.count} ${pool.get(e.cardId)!.name} (${mv(pool.get(e.cardId)!)})`).join(", ") || "— passes"} |`);
L.push("", `Passing unchanged past the Power: ${rows.filter((r) => r.nHigh === 0).length} of ${rows.length}. Losing one to four: ${rows.filter((r) => r.nHigh > 0 && r.nHigh <= 4).length}. Five or more: ${rows.filter((r) => r.nHigh > 4).length}.`, "");

// 4. the fours that stay
const fours = legal.filter((d) => mv(d) === 4);
const sweep = fours.filter((d) => JSON.stringify(d).match(/"(destroyAll|damageAll)"/));
L.push("## 4. The top of the curve that stays (mana value four)", "", `${fours.length} cards. The sweepers among them: ${sweep.map((d) => d.name).join(", ") || "none"}.`, "", fours.sort((a, b) => a.name.localeCompare(b.name)).map((d) => `${d.name} (${d.manaCost}${isCreature(d) ? `, ${d.power}/${d.toughness}` : ""})`).join("; "), "");

const text = L.join("\n") + "\n";
const out = arg("out", "");
if (out) writeFileSync(out, text);
console.log(text);
