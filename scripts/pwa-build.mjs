#!/usr/bin/env node
// Post-S71 (Chris, the iPhone Duo): the offline copy. Runs after `vite build` (scripts/build-web.sh).
// Walks packages/ui/dist and writes two files into it:
//   offline-files.json — every servable file with its size and a content hash, split into the SHELL
//     (what the app needs to open and play: code, fonts, frames, maps, the oracle) and the rest (card
//     art, portraits, audio), which is cached as it is seen or all at once from "Make available offline".
//   sw.js — packages/ui/pwa/sw-template.js with the build's version and the shell list prepended.
// The version is a hash of every file's hash, so sw.js changes (and the phone offers an update) only when
// something it would serve changed.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(repo, "packages/ui/dist");
const template = join(repo, "packages/ui/pwa/sw-template.js");

/** Not served to players (dev-only tooling) or written by this script. */
const SKIP = new Set(["sw.js", "offline-files.json"]);
/** Top-level folders that are bulk art and audio: on demand or by the download, never in the shell. */
const BULK = ["custom-art/", "portraits/", "printed-art/", "real-art/", "audio/"];
/** Exceptions inside a bulk folder that the shell needs. */
const SHELL_EXTRA = new Set(["real-art/oracle.json"]);
/** Large dev-viewer samples: not shell (the download includes them). */
const NOT_SHELL = new Set(["sample-game.json", "sample-game-sane.json"]);

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.isFile() && e.name !== ".DS_Store") out.push(p);
  }
  return out;
}

const files = walk(dist)
  .map((p) => relative(dist, p).split(sep).join("/"))
  .filter((u) => !SKIP.has(u))
  .sort();

const entries = files.map((u) => {
  const buf = readFileSync(join(dist, u));
  const h = createHash("sha1").update(buf).digest("hex").slice(0, 16);
  const shell = SHELL_EXTRA.has(u) || (!BULK.some((b) => u.startsWith(b)) && !NOT_SHELL.has(u));
  return { u: "/" + u, s: statSync(join(dist, u)).size, h, shell };
});

const version = createHash("sha1").update(entries.map((e) => e.u + ":" + e.h).join("\n")).digest("hex").slice(0, 12);
const shell = entries.filter((e) => e.shell);
const offline = { version, files: entries.map(({ u, s, h, shell: sh }) => (sh ? { u, s, h, shell: true } : { u, s, h })) };
writeFileSync(join(dist, "offline-files.json"), JSON.stringify(offline));

const head = `// GENERATED by scripts/pwa-build.mjs — do not edit; edit packages/ui/pwa/sw-template.js.\n` +
  `const BUILD = ${JSON.stringify(version)};\n` +
  `const SHELL = ${JSON.stringify(shell.map((e) => e.u))};\n`;
writeFileSync(join(dist, "sw.js"), head + readFileSync(template, "utf8"));

const mb = (n) => (n / 1048576).toFixed(1);
const total = entries.reduce((a, e) => a + e.s, 0), shellBytes = shell.reduce((a, e) => a + e.s, 0);
console.log(`pwa-build: version ${version}; shell ${shell.length} files ${mb(shellBytes)} MB; all ${entries.length} files ${mb(total)} MB`);
