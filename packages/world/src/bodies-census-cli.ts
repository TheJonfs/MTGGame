/**
 * pnpm bodies:census [--out file.md]
 *
 * Post-S71a (Chris: Bodies is the first gate format to get a field of its own — seeds, a table, then his run at it).
 * A census of the Open's creatures for Odile's gate (twenty-four creatures in sixty): each creature's colour, curve and
 * roles (removal on a body, mana, card draw, tokens, a lord, recursion, evasion, flash, a finisher); the tribes and the
 * cards that reward them; every registered list's creature count and its gap to twenty-four; and the non-creature
 * cards the creature-heavy lists already spend their slots on. It changes nothing.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadCardPool } from "@shandalar/cards/loader";
import { cardColors, manaValue, parseManaCost, type CardDef } from "@shandalar/cards";
import { FORMAT_DECKS } from "@shandalar/sim/open-decks";
import { BODIES_FORMAT } from "./formats.js";
import { cardLegal } from "./constructed-builder.js";

const arg = (k: string, d: string) => { const i = process.argv.indexOf(`--${k}`); return i >= 0 ? process.argv[i + 1]! : d; };
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const pool = loadCardPool(join(ROOT, "data/cards")).cards;
const rule = BODIES_FORMAT.rule;
const mv = (d: CardDef) => manaValue(parseManaCost(d.manaCost));
const isCreature = (d: CardDef) => d.types.includes("Creature");
const isLand = (d: CardDef) => d.types.includes("Land");
const colourKey = (d: CardDef) => { const c = cardColors(d); return c.length === 0 ? "C" : c.length > 1 ? "multi" : c[0]!; };

type Eff = { type: string; target?: unknown; to?: string; scope?: string; subtype?: string; who?: string };
const effectsOf = (d: CardDef): { kind: string; event?: string; cost?: { sacrifice?: unknown }; targets?: { predicate?: string }[]; effects: Eff[] }[] =>
  ((d.abilities ?? []) as never[]).map((a: { kind: string; event?: string; cost?: { sacrifice?: unknown }; targets?: { predicate?: string }[]; effects?: Eff[]; modes?: { effects?: Eff[]; targets?: { predicate?: string }[] }[] }) => ({ ...a, targets: [...(a.targets ?? []), ...(a.modes ?? []).flatMap((m) => m.targets ?? [])], effects: [...(a.effects ?? []), ...(a.modes ?? []).flatMap((m) => m.effects ?? [])] }));
const REMOVAL = new Set(["fight", "damage", "destroy", "bounce", "exile", "gainControl", "exileThenReturn", "tapTarget"]);
function roles(d: CardDef): string[] {
  const r = new Set<string>(), ab = effectsOf(d), kw = (d.keywords ?? []) as string[];
  for (const a of ab) {
    const targeted = (a.targets ?? []).length > 0;
    if (a.effects.some((e) => REMOVAL.has(e.type) && e.to !== "you") && (targeted || a.effects.some((e) => e.type === "damage"))) r.add("removal");
    if (a.effects.some((e) => e.type === "addMana")) r.add("mana");
    if (a.effects.some((e) => e.type === "draw" || e.type === "searchLibrary")) r.add("cards");
    if (a.effects.some((e) => e.type === "createToken")) r.add("tokens");
    if (a.kind === "static" && a.effects.some((e) => (e.type === "modifyPT" || e.type === "grantKeyword") && e.scope === "creaturesYouControl")) r.add("lord");
    if (a.effects.some((e) => e.type === "returnFromGraveyard")) r.add("recursion");
    if (a.effects.some((e) => e.type === "gainLife")) r.add("life");
    if (a.cost?.sacrifice) r.add("sac outlet");
    if (a.effects.some((e) => e.type === "discard" || e.type === "mill")) r.add("disruption");
  }
  if (kw.includes("lifelink")) r.add("life");
  if (kw.some((k) => ["flying", "menace", "trample", "shadow"].includes(k))) r.add("evasion");
  if (kw.includes("flash")) r.add("flash");
  if (kw.includes("defender")) r.add("wall");
  if ((d.power ?? 0) >= 5) r.add("finisher");
  return [...r];
}

const legal = [...pool.values()].filter((d) => !d.isTokenDef && cardLegal(d, rule));
const creatures = legal.filter(isCreature).sort((a, b) => mv(a) - mv(b) || a.name.localeCompare(b.name));
const L: string[] = [];
L.push(`# Bodies — a census of the Open's creatures (post-S71a)`, "", `*Generated by \`pnpm bodies:census\`. Bodies is the Open's pool and restricted list with one rule: twenty-four creatures in sixty (\`minCreatures: 24\`). Nothing else changes, so the Open's mana (duals, the High Grounds, the Moxen) is all here.*`, "");
L.push(`**${creatures.length} creatures** legal (prize-only cards marked ★). Roles are read from the card definitions: *removal* (a targeted removal effect on the body, on entering, attacking, dying or activated), *mana*, *cards* (draw or search), *tokens*, *lord* (pumps or grants to our creatures), *recursion*, *life*, *sac outlet*, *disruption* (discard, mill), *evasion* (flying, menace, trample), *flash*, *wall* (defender), *finisher* (power five or more).`, "");

// 1. by colour, the curve and the roles
const COLS = ["W", "U", "B", "R", "G", "multi", "C"];
const NAME: Record<string, string> = { W: "White", U: "Blue", B: "Black", R: "Red", G: "Green", multi: "Multicolour", C: "Colourless" };
L.push("## 1. By colour", "", "| colour | creatures | MV 1 | 2 | 3 | 4 | 5 | 6+ | removal | mana | cards | tokens | lord | evasion | flash | finisher |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
for (const c of COLS) {
  const xs = creatures.filter((d) => colourKey(d) === c), at = (n: number) => xs.filter((d) => (n === 6 ? mv(d) >= 6 : mv(d) === n)).length, role = (k: string) => xs.filter((d) => roles(d).includes(k)).length;
  const low = xs.filter((d) => mv(d) <= 1).length;
  L.push(`| ${NAME[c]} | ${xs.length} | ${low} | ${at(2)} | ${at(3)} | ${at(4)} | ${at(5)} | ${at(6)} | ${role("removal")} | ${role("mana")} | ${role("cards")} | ${role("tokens")} | ${role("lord")} | ${role("evasion")} | ${role("flash")} | ${role("finisher")} |`);
}
L.push("");
for (const c of COLS) {
  const xs = creatures.filter((d) => colourKey(d) === c);
  if (!xs.length) continue;
  L.push(`### ${NAME[c]} (${xs.length})`, "");
  for (const d of xs) L.push(`- **${d.name}**${(d as { prizeOnly?: boolean }).prizeOnly ? " ★" : ""} ${d.manaCost} ${d.power}/${d.toughness}${(d.subtypes ?? []).length ? ` — ${(d.subtypes ?? []).join(" ")}` : ""}${roles(d).length ? ` · ${roles(d).join(", ")}` : ""}${typeof d.shopTier === "number" ? ` · tier ${d.shopTier}` : ""}`);
  L.push("");
}

// 2. the tribes
const json = (d: CardDef) => JSON.stringify(d);
const tribes = new Map<string, CardDef[]>();
for (const d of creatures) for (const s of d.subtypes ?? []) tribes.set(s, [...(tribes.get(s) ?? []), d]);
L.push("## 2. Tribes (three or more members) and the cards that reward them", "", "A rewarder is any legal card whose definition names the subtype (a lord, a tutor, a payoff) — read the card before trusting it.", "");
for (const [s, ms] of [...tribes].filter(([, ms]) => ms.length >= 3).sort((a, b) => b[1].length - a[1].length)) {
  const re = new RegExp(`"(subtype|subtypes)":\\s*(\\[[^\\]]*)?"${s}"`);
  const rewards = legal.filter((d) => re.test(json(d).replace(/"subtypes":\s*\[[^\]]*\]/, ""))).map((d) => d.name);
  L.push(`- **${s}** (${ms.length}): ${ms.map((d) => `${d.name} (${mv(d)})`).join(", ")}${rewards.length ? `\n  - rewarded by: ${rewards.join(", ")}` : ""}`);
}
L.push("");

// 3. the registered lists
type List = { key: string; name: string; archetype: string; decklist: { cardId: string; count: number }[]; archived?: boolean };
const rows: { f: string; l: List; cr: number; lands: number; other: number }[] = [];
for (const [f, ls] of Object.entries(FORMAT_DECKS)) for (const l of Object.values(ls) as List[]) {
  const n = (p: (d: CardDef) => boolean) => l.decklist.reduce((a, e) => a + (pool.get(e.cardId) && p(pool.get(e.cardId)!) ? e.count : 0), 0);
  rows.push({ f, l, cr: n(isCreature), lands: n(isLand), other: n((d) => !isCreature(d) && !isLand(d)) });
}
const seen = new Set<string>();
const uniq = rows.sort((a, b) => b.cr - a.cr).filter((r) => { const k = JSON.stringify([...r.l.decklist].sort((x, y) => x.cardId.localeCompare(y.cardId))); if (seen.has(k)) return false; seen.add(k); return true; });
L.push("## 3. Registered lists by creature count (every format, archived included; a list repeated across formats shown once)", "", "| creatures | gap to 24 | lands | other | list | format | archetype |", "|---|---|---|---|---|---|---|");
for (const r of uniq.filter((r) => r.cr >= 16)) L.push(`| ${r.cr} | ${Math.max(0, 24 - r.cr)} | ${r.lands} | ${r.other} | ${r.l.name}${r.l.archived ? " (archived)" : ""} | ${r.f} | ${r.l.archetype} |`);
L.push("", `Lists under sixteen creatures: ${uniq.filter((r) => r.cr < 16).length}.`, "");

// 4. what the creature-heavy lists spend their other slots on
const heavy = uniq.filter((r) => r.cr >= 18);
const use = new Map<string, { lists: string[]; copies: number }>();
for (const r of heavy) for (const e of r.l.decklist) { const d = pool.get(e.cardId); if (!d || isCreature(d) || isLand(d)) continue; const u = use.get(d.name) ?? { lists: [], copies: 0 }; u.lists.push(r.l.name); u.copies += e.count; use.set(d.name, u); }
L.push(`## 4. The non-creature, non-land cards in the ${heavy.length} lists with eighteen or more creatures`, "", "| card | lists | copies | in |", "|---|---|---|---|");
for (const [n, u] of [...use].sort((a, b) => b[1].lists.length - a[1].lists.length || b[1].copies - a[1].copies)) L.push(`| ${n} | ${u.lists.length} | ${u.copies} | ${[...new Set(u.lists)].join(", ")} |`);
L.push("");

const text = L.join("\n") + "\n";
const out = arg("out", "");
if (out) writeFileSync(out, text);
console.log(text);
